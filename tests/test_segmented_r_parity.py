@pytest.mark.parametrize(
    "case",
    _LWP_WRAPPER_SINGLE_OBS,
    ids=lambda c: f"lwp_wrapper_{c['case']}",
)
def test_per_segment_direct_10_metric_parity_with_r_lwp_trends(case):
    """Compare all 10 metrics directly against R LWP-TRENDS v2502 wrapper outputs."""
    vals = [np.nan if v == "NA" else v for v in case["values"]]
    x_df = mk.prepare_censored_data(vals)
    t = pd.to_datetime(case["dates"]).to_numpy()
    common = dict(
        alpha=0.10,
        mk_test_method="lwp",
        ci_method="lwp",
        sens_slope_method="lwp",
        tau_method="a",
        tie_break_method="lwp",
        slope_scaling="year",
    )
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        st = segmented_trend_test(x_df, t, n_breakpoints=0, **common)

    seg = st.segments.iloc[0]
    fields = {
        "S": "s", "VarS": "var_s", "tau": "Tau", "Z": "z", "p": "p",
        "C": "C", "Cd": "Cd", "slope": "slope", "lower_ci": "lower_ci", "upper_ci": "upper_ci",
    }
    for rkey, pkey in fields.items():
        expected = float(case["R"][rkey])
        got = float(seg[pkey])
        if abs(expected) < 1e-12:
            assert abs(got) < 1e-9, (rkey, got, expected)
        else:
            assert got == pytest.approx(expected, rel=1e-6), (rkey, got, expected)


@pytest.mark.parametrize(
    "kc",
    LWP_FIXTURES["kernel"][:8],
    ids=lambda c: f"lwp_kernel_{c['case']}",
)
def test_per_segment_exact_parity_with_lwp_kernel_and_trend_test(kc):
    raw = [
        f"<{v}" if c == "lt" else (f">{v}" if c == "gt" else str(v))
        for v, c in zip(kc["values"], kc["cen_type"])
    ]
    x_df = mk.prepare_censored_data(raw)
    t = pd.to_datetime(kc["dates"]).to_numpy()
    common = dict(
        alpha=0.10,
        mk_test_method="lwp",
        ci_method="lwp",
        sens_slope_method="lwp",
        tau_method="a",
        tie_break_method="lwp",
        slope_scaling="year",
    )
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        tt = mk.trend_test(x_df, t, **common)
        st = segmented_trend_test(x_df, t, n_breakpoints=0, **common)

    seg = st.segments.iloc[0]
    assert int(seg["s"]) == int(kc["R"]["S"])
    assert float(seg["var_s"]) == pytest.approx(float(kc["R"]["VarS"]), rel=1e-12)
    assert float(seg["slope"]) == pytest.approx(float(kc["R"]["sen"]), rel=1e-9)

    for col in ("s", "var_s", "z", "p", "Tau", "C", "Cd", "slope", "lower_ci", "upper_ci"):
        got = float(seg[col])
        exp = float(getattr(tt, col))
        if np.isnan(exp):
            assert np.isnan(got)
        elif abs(exp) < 1e-12:
            assert abs(got) < 1e-9
        else:
            assert got == pytest.approx(exp, rel=1e-9), (col, got, exp)


def test_selection_summary_score_matches_ess_selection():
    """Verify ESS actually triggers on strong AR(1), score differs from raw BIC,
    k=0 score is deterministic across seeds, and argmin(score) == n_breakpoints."""
    rng = np.random.default_rng(202607)
    n = 100
    t = np.arange(n, dtype=float)
    eps = rng.normal(0.0, np.sqrt(1.0 - 0.7 ** 2), size=n)
    y = np.empty(n)
    y[0] = rng.normal(0.0, 1.0)
    for i in range(1, n):
        y[i] = 0.7 * y[i - 1] + eps[i]
    y = 10.0 + 0.05 * t + y

    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        res1 = segmented_trend_test(
            y, t, max_breakpoints=2, criterion="bic",
            autocorr_penalty="auto", random_state=42,
        )
        res2 = segmented_trend_test(
            y, t, max_breakpoints=2, criterion="bic",
            autocorr_penalty="auto", random_state=99,
        )

    ss = res1.selection_summary
    assert "score" in ss.columns
    valid = ss[ss["converged"] & np.isfinite(ss["score"])]
    assert not valid.empty
    # Verify ESS actually triggered (score differs from unadjusted bic)
    assert not np.allclose(valid["score"], valid["bic"])
    # Verify k=0 ESS score is identical across seeds (H1)
    k0_1 = float(ss.loc[ss["n_breakpoints"] == 0, "score"].iloc[0])
    k0_2 = float(res2.selection_summary.loc[res2.selection_summary["n_breakpoints"] == 0, "score"].iloc[0])
    assert k0_1 == pytest.approx(k0_2, rel=0.0, abs=1e-12)
    best_row = valid.loc[valid["score"].idxmin()]
    assert int(best_row["n_breakpoints"]) == res1.n_breakpoints
    assert float(best_row["score"]) == pytest.approx(float(res1.score), rel=1e-12)
