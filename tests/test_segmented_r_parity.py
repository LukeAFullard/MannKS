def test_globTempAnom_seed_invariance_and_rss_parity_across_10_seeds():
    """H1 regression: globTempAnom must select the exact same k across 10 seeds
    (for both autocorr_penalty='none' and 'auto') and match CRAN segmented RSS."""
    case = [
        c for c in SEG_FIXTURES["published"]
        if c["dataset"] == "globTempAnom" and c["mode"] == "select"
    ][0]
    t = np.asarray(case["t"], dtype=float)
    y = np.asarray(case["y"], dtype=float)
    r_bps = np.sort(np.asarray(case["R"]["bps"], dtype=float))
    r_rss = _profile_rss_orig(t, y, r_bps)

    ks_none = []
    ks_auto = []
    k0_scores_auto = []
    for seed in range(10):
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            r_none = segmented_trend_test(
                y, t, max_breakpoints=3, criterion="bic",
                autocorr_penalty="none", random_state=seed,
            )
            r_auto = segmented_trend_test(
                y, t, max_breakpoints=3, criterion="bic",
                autocorr_penalty="auto", random_state=seed,
            )
        ks_none.append(r_none.n_breakpoints)
        ks_auto.append(r_auto.n_breakpoints)
        ss_a = r_auto.selection_summary
        k0_scores_auto.append(float(ss_a.loc[ss_a["n_breakpoints"] == 0, "score"].iloc[0]))
        k3_rss = float(
            r_none.selection_summary.loc[r_none.selection_summary["n_breakpoints"] == 3, "rss"].iloc[0]
        )
        assert k3_rss <= r_rss * (1.0 + 1e-3)

    assert ks_none == [3] * 10
    assert len(set(ks_auto)) == 1
    assert np.allclose(k0_scores_auto, k0_scores_auto[0], rtol=0.0, atol=1e-12)


