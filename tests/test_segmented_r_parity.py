"""
Parity tests for `segmented_trend_test` against frozen reference outputs from:
  1. CRAN `segmented` (v2.0-3, Muggeo 2003/2008/2020) stored in
     ``tests/data/segmented_r_parity_fixtures.json`` (generated by
     ``validation/r_parity/segmented_parity.py``).
  2. R `LWP-TRENDS` (v2502) stored in ``tests/data/lwp_parity_fixtures.json``.

These tests run without R in CI and verify cross-package numerical agreement.
"""
import json
import os
import warnings

import numpy as np
import pandas as pd
import pytest

import MannKS as mk
from MannKS import segmented_trend_test

DATA_DIR = os.path.join(os.path.dirname(__file__), "data")

with open(os.path.join(DATA_DIR, "segmented_r_parity_fixtures.json")) as fh:
    SEG_FIXTURES = json.load(fh)

with open(os.path.join(DATA_DIR, "lwp_parity_fixtures.json")) as fh:
    LWP_FIXTURES = json.load(fh)


@pytest.mark.parametrize(
    "case",
    [c for c in SEG_FIXTURES["published"] if c["mode"] == "fixed"],
    ids=lambda c: c["case_id"],
)
def test_published_datasets_fixed_k_matches_r_segmented(case):
    t = np.asarray(case["t"], dtype=float)
    y = np.asarray(case["y"], dtype=float)
    k_fixed = int(case["k_fixed"])
    r_bps = np.sort(np.asarray(case["R"]["bps"], dtype=float))
    r_slopes = np.asarray(case["R"]["slopes"], dtype=float)
    t_span = float(np.max(t) - np.min(t))

    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        res = segmented_trend_test(
            y, t, n_breakpoints=k_fixed, criterion="bic",
            autocorr_penalty="none", random_state=42,
        )

    assert res.n_breakpoints == case["R"]["n_bp"] == k_fixed
    mk_bps = np.sort(np.asarray(res.breakpoints, dtype=float))
    assert len(mk_bps) == k_fixed

    # For well-identified datasets (stagnant, plant_*), breakpoints agree tightly
    # with CRAN segmented (< 3.5% of time span). globTempAnom (n=174, strongly
    # autocorrelated with 3 breaks) has multiple close Muggeo local minima.
    if case["dataset"] != "globTempAnom":
        max_rel_diff = float(np.max(np.abs(mk_bps - r_bps))) / t_span
        assert max_rel_diff < 0.035, (
            f"{case['dataset']}: mk_bps={mk_bps}, r_bps={r_bps}, rel_diff={max_rel_diff:.4f}"
        )
        # Segment Sen slopes should share signs with CRAN segmented OLS slopes
        mk_slopes = res.segments["slope"].to_numpy(dtype=float)
        assert len(mk_slopes) == len(r_slopes)
        for s_mk, s_r in zip(mk_slopes, r_slopes):
            if abs(s_r) > 1e-3:
                assert np.sign(s_mk) == np.sign(s_r)
    else:
        # Ensure all 3 breakpoints are strictly interior and ordered
        assert np.all(np.diff(mk_bps) > 0)
        assert mk_bps[0] > t.min() and mk_bps[-1] < t.max()


@pytest.mark.parametrize(
    "case",
    [
        c for c in SEG_FIXTURES["published"]
        if c["mode"] == "select" and c["dataset"] != "globTempAnom"
    ],
    ids=lambda c: c["case_id"],
)
def test_published_datasets_auto_bic_matches_r_selgmented(case):
    t = np.asarray(case["t"], dtype=float)
    y = np.asarray(case["y"], dtype=float)
    t_span = float(np.max(t) - np.min(t))

    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        res = segmented_trend_test(
            y, t, max_breakpoints=int(case["k_max"]), criterion="bic",
            autocorr_penalty="none", random_state=42,
        )

    assert res.n_breakpoints == case["R"]["n_bp"]
    if res.n_breakpoints > 0:
        mk_bps = np.sort(np.asarray(res.breakpoints, dtype=float))
        r_bps = np.sort(np.asarray(case["R"]["bps"], dtype=float))
        assert float(np.max(np.abs(mk_bps - r_bps))) / t_span < 0.035


@pytest.mark.parametrize(
    "case",
    SEG_FIXTURES["synthetic"],
    ids=lambda c: c["case_id"],
)
def test_planted_truth_synthetic_matches_r_segmented(case):
    t = np.asarray(case["t"], dtype=float)
    y = np.asarray(case["y"], dtype=float)
    true_k = int(case["true_k"])

    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        res = segmented_trend_test(
            y, t, max_breakpoints=2, criterion="bic",
            autocorr_penalty="none", random_state=42,
        )

    assert res.n_breakpoints == case["R"]["n_bp"] == true_k
    if true_k > 0:
        mk_bps = np.sort(np.asarray(res.breakpoints, dtype=float))
        r_bps = np.sort(np.asarray(case["R"]["bps"], dtype=float))
        assert np.max(np.abs(mk_bps - r_bps)) < 1.0, f"mk_bps={mk_bps}, r_bps={r_bps}"

        mk_slopes = res.segments["slope"].to_numpy(dtype=float)
        true_slopes = np.asarray(case["true_slopes"], dtype=float)
        assert np.max(np.abs(mk_slopes - true_slopes)) < 0.08


@pytest.mark.parametrize(
    "kc",
    LWP_FIXTURES["kernel"][:8],
    ids=lambda c: f"lwp_kernel_{c['case']}",
)
def test_per_segment_exact_parity_with_lwp_trends(kc):
    raw = [
        f"<{v}" if c == "lt" else (f">{v}" if c == "gt" else str(v))
        for v, c in zip(kc["values"], kc["cen_type"])
    ]
    x_df = mk.prepare_censored_data(raw)
    t = pd.to_datetime(kc["dates"]).to_numpy()
    common = dict(
        alpha=0.10,
        mk_test_method="lwp",
        ci_method="lwp",
        sens_slope_method="lwp",
        tau_method="a",
        tie_break_method="lwp",
        slope_scaling="year",
    )
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        tt = mk.trend_test(x_df, t, **common)
        st = segmented_trend_test(x_df, t, n_breakpoints=0, **common)

    seg = st.segments.iloc[0]
    assert int(seg["s"]) == int(kc["R"]["S"])
    assert float(seg["var_s"]) == pytest.approx(float(kc["R"]["VarS"]), rel=1e-12)
    assert float(seg["slope"]) == pytest.approx(float(kc["R"]["sen"]), rel=1e-9)

    for col in ("s", "var_s", "z", "p", "Tau", "C", "Cd", "slope", "lower_ci", "upper_ci"):
        got = float(seg[col])
        exp = float(getattr(tt, col))
        if np.isnan(exp):
            assert np.isnan(got)
        elif abs(exp) < 1e-12:
            assert abs(got) < 1e-9
        else:
            assert got == pytest.approx(exp, rel=1e-9), (col, got, exp)


def test_selection_summary_score_matches_ess_selection():
    """Verify selection_summary['score'] reflects the ESS-adjusted objective."""
    rng = np.random.default_rng(202607)
    n = 100
    t = np.arange(n, dtype=float)
    eps = rng.normal(0.0, np.sqrt(1.0 - 0.6 ** 2), size=n)
    y = np.empty(n)
    y[0] = rng.normal(0.0, 1.0)
    for i in range(1, n):
        y[i] = 0.6 * y[i - 1] + eps[i]
    y = 10.0 + 0.05 * t + y

    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        res = segmented_trend_test(
            y, t, max_breakpoints=2, criterion="bic",
            autocorr_penalty="auto", random_state=42,
        )

    ss = res.selection_summary
    assert "score" in ss.columns
    valid = ss[ss["converged"] & np.isfinite(ss["score"])]
    assert not valid.empty
    best_row = valid.loc[valid["score"].idxmin()]
    assert int(best_row["n_breakpoints"]) == res.n_breakpoints
    assert float(best_row["score"]) == pytest.approx(float(res.score), rel=1e-12)
